#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_table_agent_has_its_spec() {
        for kind in AgentKind::ALL {
            if let Some(spec) = of(kind) {
                assert_eq!(spec.kind, kind, "{}", spec.id);
                assert_eq!(kind.as_str(), spec.id);
                assert!(!spec.binaries.is_empty(), "{}", spec.id);
            }
        }
        assert_eq!(ALL.len() + 6, AgentKind::ALL.len());
        for spec in ALL {
            assert_eq!(of(spec.kind), Some(spec));
        }
    }

    #[test]
    fn names_do_not_collide() {
        let mut seen = std::collections::HashMap::new();
        for kind in AgentKind::ALL {
            let mut names = vec![kind.as_str()];
            if let Some(s) = of(kind) {
                names.extend(s.aliases);
            }
            for n in names {
                if let Some(other) = seen.insert(n, kind) {
                    panic!("`{n}` names both {other} and {kind}");
                }
                assert_eq!(n.parse::<AgentKind>(), Ok(kind), "{n}");
            }
        }
    }

    #[test]
    fn pinned_flags_survive_operator_extra_args() {
        // A pinned flag that is also unsafe cannot be overridden: the
        // operator's copy is stripped and the pinned one stays.
        for spec in ALL {
            let mut cfg = super::super::AgentConfig::default_for(spec.kind);
            cfg.extra_args = spec.unsafe_flags.iter().map(|f| (*f).to_owned()).collect();
            let inv = super::super::Invocation {
                prompt: "hi",
                resume: None,
                model: None,
            };
            let args: Vec<String> = super::super::spec::build_args(spec, &cfg, inv)
                .into_iter()
                .map(|a| a.to_string_lossy().into_owned())
                .collect();
            for group in spec.pinned_args {
                assert!(
                    args.contains(&group[0].to_owned()),
                    "{}: {}",
                    spec.id,
                    group[0]
                );
            }
        }
    }

    #[test]
    fn pinned_and_base_args_are_flags_or_values() {
        for spec in ALL {
            assert!(
                spec.pinned_args.iter().all(|g| !g.is_empty()),
                "{}",
                spec.id
            );
            assert!(
                spec.limit_messages.iter().all(|m| *m == m.to_lowercase()),
                "{}",
                spec.id
            );
        }
    }
}
